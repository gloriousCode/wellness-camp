#!/usr/bin/env python3
"""Build a local gameplay layer, retaining normal atlas imagery in uncaptured cells."""

import argparse
import hashlib
import json
from pathlib import Path

from PIL import Image


def public_provenance(value):
    """Keep useful repair evidence without publishing local filesystem paths."""
    if isinstance(value, dict):
        return {key: public_provenance(item) for key, item in value.items()}
    if isinstance(value, list):
        return [public_provenance(item) for item in value]
    if isinstance(value, str) and (Path(value).is_absolute() or value.startswith('.local/')):
        return Path(value).name
    return value


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("rooms", type=Path, help="Private rooms.json produced during recording analysis")
    parser.add_argument("--atlas", type=Path, default=Path("public/maps/20240603_4757794989373292024.webp"))
    parser.add_argument("--map-id", default="20240603_4757794989373292024")
    parser.add_argument("--date", default="2026-10-20")
    args = parser.parse_args()
    source = json.loads(args.rooms.read_text())
    atlas = Image.open(args.atlas).convert("RGB")
    rooms = []
    seen = set()
    for room in source["rooms"]:
        column, row = room["column"], room["row"]
        room_id = f"{column:02d},{row:02d}"
        x, y = column * 320, row * 176
        if room_id in seen or x < 0 or y < 0 or x + 320 > atlas.width or y + 176 > atlas.height:
            raise ValueError(f"Invalid or repeated atlas cell: {room_id}")
        seen.add(room_id)
        with Image.open(args.rooms.parent / room["image"]) as image:
            if list(image.size) != source["image_size"]:
                raise ValueError(f"Unexpected source size: {room['image']}")
            atlas.paste(image.convert("RGB").resize((320, 176), Image.Resampling.BOX), (x, y))
        entry = {"id": room_id, "seconds": room["seconds"], "score": room["score"], "margin": room["margin"]}
        if room.get("temporalMerge"):
            entry["temporalMerge"] = room["temporalMerge"]
        if room.get("reviewEvidence"):
            entry["reviewEvidence"] = room["reviewEvidence"]
        for field in ('inferredLocation', 'cursorRepair', 'playerRepair'):
            if room.get(field):
                entry[field] = public_provenance(room[field])
        rooms.append(entry)
    output = Path("public/gameplay")
    output.mkdir(parents=True, exist_ok=True)
    name = args.date.replace("-", "")
    file = output / f"{name}.webp"
    # Lossless encoding keeps uncaptured cells identical to the decoded normal atlas.
    atlas.save(file, lossless=True, method=4)
    descriptor = {"mapId": args.map_id, "file": f"gameplay/{name}.webp", "date": args.date,
                  "cellBounds": source.get("coverage", {}).get("cellBounds"),
                  "roomIds": [room["id"] for room in rooms],
                  "mergedRoomIds": [room["id"] for room in rooms if room.get("temporalMerge")],
                  "inferredRoomIds": [room["id"] for room in rooms if room.get("inferredLocation")],
                  "repairedRoomIds": [room["id"] for room in rooms if room.get("cursorRepair", {}).get("changed_pixels", 0) or room.get("playerRepair", {}).get("changes")]}
    metadata = {**descriptor, "sourceRecording": Path(source["recording"]).name,
                "sourceCrop": source["crop"], "width": atlas.width, "height": atlas.height,
                "bytes": file.stat().st_size, "sha256": hashlib.sha256(file.read_bytes()).hexdigest(),
                "status": "Candidate room matches; not all placements have been manually verified",
                "fallback": "Uncaptured cells retain the normal atlas",
                "cleanup": source.get("processing", "None; player, HUD, cursor and gameplay effects remain"),
                "rooms": rooms}
    if source.get("coverage"):
        metadata["coverage"] = source["coverage"]
    if source.get('playerRepair'):
        metadata['playerRepairSummary'] = public_provenance(source['playerRepair'])
    (output / f"{name}.json").write_text(json.dumps(metadata, indent=2) + "\n")
    Path("src/gameplay.ts").write_text(
        "// Generated by scripts/build_gameplay_atlas.py from the local recording analysis.\n"
        + "export const GAMEPLAY_ATLAS = " + json.dumps(descriptor, indent=2) + " as const;\n")
    print(f"Built {file}: {len(rooms)} captured cells, {file.stat().st_size:,} bytes")


if __name__ == "__main__":
    main()
